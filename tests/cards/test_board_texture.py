def cards_for(spec: str) -> list[Card]:
    """Parse a whitespace-separated symbol list, e.g. ``"As Kd Qs"``."""
    return [Card(symbol[:-1], symbol[-1]) for symbol in spec.split()]


def card_for(symbol: str) -> Card:
    """Parse a single two-character symbol, e.g. ``"As"``."""
    return Card(symbol[:-1], symbol[-1])


_SUIT_ALPHABET = "cdhs"
_SUIT_ALPHABET_BUFE = b"cdhs"
_SUIT_PERMS = tuple(itertools.permutations(_SUIT_ALPHABET))
_SUIT_TRANSLATION_TABLES = tuple(
    bytes.maketrans(_SUIT_ALPHABET_BUFE, "".join(perm).encode())
    for perm in _SUIT_PERMS
)


def _translate_suits(suits, table) -> bytes:
    """Relabel a byte-level suit sequence under one suit permutation."""
    return suits.translate(table)


def _translate_suits(suits: bytes, table) -> bytes:
    """Relabel a byte-level suit sequence under one suit permutation."""
    return suits.translate(table)


def _canonical_suit_reps(multiplicities: tuple[int, ...]) -> list[bytes]:
    """One canonical representative per S4 suit orbit of a rank multiset.

    Cards are ordered group by group (``multiplicities`` descending, aligned
    with ``_multiset_board``); within a group all suits must be distinct
    (same rank => distinct cards).  The restricted-growth rule — a new suit
    is always the next unused letter of ``cdhs`` — emits exactly one member
    per orbit, because any valid assignment can be relabeled so that first
    occurrences appear in ``cdhs`` order.  Represented as bytes for speed;
    group g uses rank ``RANKS[g]``.
    """
    total = sum(multiplicities)
    reps: list[bytes] = []

    def extend(position: int, used: bytes, assignment: bytearray) -> None:
        if position == total:
            reps.append(bytes(assignment))
            return
        offset = 0
        for size in multiplicities:
            if position < offset + size:
                break
            offset += size
        group_used = assignment[offset:position]
        for suit in used:
            if suit not in group_used:
                assignment.append(suit)
                extend(position + 1, used, assignment)
                assignment.pop()
        if len(used) < len(_SUIT_ALPHABET):
            new_suit = _SUIT_ALPHABET_BUFE[len(used)]
            assignment.append(new_suit)
            extend(position + 1, used + bytes([new_suit]), assignment)
            assignment.pop()

    extend(0, b"", bytearray())
    return reps


def _multiset_board(multiplicities: tuple[int, ...], suits: bytes) -> list[Card]:
    """Build a real board from a descending multiplicity tuple and suit reps.

    Group ``g`` takes rank ``RANKS[g]`` (so multiplicities pair with the
    lowest ranks; the pairing choice is irrelevant for coverage because rank
    identities are enumerated exhaustively elsewhere).
    """
    letters = suits.decode()
    cards: list[Card] = []
    index = 0
    for group, size in enumerate(multiplicities):
        rank = RANKS[group]
        for _ in range(size):
            cards.append(Card(rank, letters[index]))
            index += 1
    return cards


def _valid_suit_assignments(multiplicities: tuple[int, ...]) -> list[bytes]:
    """All suit-label assignments that form a real (no duplicate card) board."""
    group_index: list[int] = []
    for group, size in enumerate(multiplicities):
        group_index.extend([group] * size)
    assignments: list[bytes] = []
    for combo in itertools.product(_SUIT_ALPHABET_BUFE, repeat=len(group_index)):
        used_in_group: dict[int, set[int]] = {}
        valid = True
        for slot, suit in enumerate(combo):
            group = group_index[slot]
            seen = used_in_group.setdefault(group, set())
            if suit in seen:
                valid = False
                break
            seen.add(suit)
        if valid:
            assignments.append(bytes(combo))
    return assignments


# --------------------------------------------------------------------- oracle
# Independent definition-driven classifier (test-module-only).  It re-derives
# every BoardTexture field from first principles; the window count uses dict
# membership arithmetic per window, deliberately different from the
# production frozenset-intersection scan.


def oracle_classify(cards) -> BoardTexture:
    """Definition-driven independent ``BoardTexture`` classifier."""
    board_cards = list(cards)
    board_size = len(board_cards)
    strength_counts: dict[int, int] = {}
    suit_counts: dict[str, int] = {}
    for card in board_cards:
        strength = RANKS.index(card.rank) + 2
        strength_counts[strength] = strength_counts.get(strength, 0) + 1
        suit_counts[card.suit] = suit_counts.get(card.suit, 0) + 1
    multiplicities = tuple(sorted(strength_counts.values(), reverse=True))

    has_quad = multiplicities[0] == 4
    has_trip = multiplicities[0] == 3
    pair_total = sum(1 for size in multiplicities if size == 2)
    if has_quad:
        pairedness = "quads"
    elif has_trip and pair_total >= 1:
        pairedness = "full-house"
    elif has_trip:
        pairedness = "trips"
    elif pair_total >= 2:
        pairedness = "two-paired"
    elif pair_total == 1:
        pairedness = "one-pair"
    else:
        pairedness = "no-pair"

    distinct_suits = len(suit_counts)
    max_suit_count = max(suit_counts.values())
    if distinct_suits == 1:
        suitedness = "monotone"
    elif distinct_suits == 2:
        suitedness = "two-tone"
    else:
        suitedness = "rainbow"

    one_away_flush_suits = sum(
        1 for count in suit_counts.values() if count == board_size - 1
    )

    high_strength = max(strength_counts)
    high_rank = RANKS[high_strength - 2]
    if high_strength < 10:
        high_band = "low"
    elif high_strength < 12:
        high_band = "mid"
    elif high_strength < 14:
        high_band = "high"
    else:
        high_band = "superhigh"

    windows = [range(start, start + 5) for start in range(2, 11)]
    windows.append((14, 2, 3, 4, 5))
    straight_windows_available = 0
    straight_windows_complete = 0
    for window in windows:
        present = sum(1 for strength in window if strength in strength_counts)
        if present >= 3:
            straight_windows_available += 1
        if present == 5:
            straight_windows_complete += 1

    return BoardTexture(
        board_size=board_size,
        rank_multiplicities=multiplicities,
        pairedness=pairedness,
        suitedness=suitedness,
        max_suit_count=max_suit_count,
        one_away_flush_suits=one_away_flush_suits,
        high_rank=high_rank,
        high_band=high_band,
        straight_windows_available=straight_windows_available,
        straight_windows_complete=straight_windows_complete,
    )


