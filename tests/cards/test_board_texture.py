class FixtureHelpersTest(unittest.TestCase):
    """Definition-level checks on the in-module representative machinery."""

    def test_rep_builder_one_per_orbit_on_flop_multisets(self):
        # Brute-force 24-permutation orbit reduction, full cross-check n=3.
        for ranks in itertools.combinations_with_replacement(RANKS, 3):
            with self.subTest(ranks=ranks):
                multiplicities = tuple(
                    sorted(Counter(ranks).values(), reverse=True)
                )
                reps = _canonical_suit_reps(multiplicities)
                self.assertTrue(reps)
                self.assertEqual(len(set(reps)), len(reps))
                self._assert_orbit_one_to_one(multiplicities, reps)

    def test_rep_builder_one_per_orbit_sampled_higher_streets(self):
        # Sampled per the docstring runtime reduction (every 25th / 100th).
        for size, stride in ((4, 25), (5, 100)):
            combos = itertools.combinations_with_replacement(RANKS, size)
            for index, ranks in enumerate(combos):
                if index % stride:
                    continue
                if size == 5 and len(set(ranks)) == 1:
                    continue  # impossible rank-multiplicity-5 board
                with self.subTest(size=size, index=index, ranks=ranks):
                    multiplicities = tuple(
                        sorted(Counter(ranks).values(), reverse=True)
                    )
                    reps = _canonical_suit_reps(multiplicities)
                    self.assertTrue(reps)
                    self.assertEqual(len(set(reps)), len(reps))
                    self._assert_orbit_one_to_one(multiplicities, reps)

    def _assert_orbit_one_to_one(self, multiplicities, reps):
        assignments = _valid_suit_assignments(multiplicities)
        self.assertTrue(assignments)
        orbits: dict[bytes, set[bytes]] = {}
        for assignment in assignments:
            canonical = min(
                assignment.translate(table)
                for table in _SUIT_TRANSLATION_TABLES
            )
            orbits.setdefault(canonical, set()).add(assignment)
        self.assertEqual(len(orbits), len(reps))
        rep_set = set(reps)
        for canonical, members in orbits.items():
            full_orbit = {
                member.translate(table)
                for member in members
                for table in _SUIT_TRANSLATION_TABLES
            }
            hits = full_orbit & rep_set
            self.assertEqual(
                len(hits), 1,
                f"orbit {canonical!r} hits {len(hits)} reps of {reps!r}",
            )


class RunoutDeltaFixtureTest(unittest.TestCase):
    """Hand-computed RunoutDelta fixtures incl. wheel edges (c)."""

    def test_runout_fixtures(self):
        for number, fixture in enumerate(RUNOUT_FIXTURES):
            with self.subTest(fixture=number):
                board = cards_for(fixture["board"])
                runout = card_for(fixture["runout"])
                delta = runout_delta(board, runout)
                expect = fixture["expect"]
                self.assertTrue(isinstance(delta, RunoutDelta))
                self.assertEqual(delta.card, runout)
                after = delta.texture_after
                self.assertEqual(after, classify(board + [runout]))
                for field, value in expect.items():
                    if field.startswith("after_"):
                        attribute = (
                            "board_size" if field == "after_board_size"
                            else field[len("after_"):]
                        )
                        target = getattr(after, attribute)
                        self.assertEqual(
                            target, value, f"{field}: {target!r} != {value!r}"
                        )
                    else:
                        self.assertEqual(
                            getattr(delta, field), value,
                            f"{field}: {getattr(delta, field)!r} != {value!r}",
                        )

    def test_wheel_ladder_two_step(self):
        """Flop 543 -> 2 -> Ace ladder reaches a complete 5-high wheel."""
        board = cards_for("5c 4d 3h")
        first = runout_delta(board, card_for("2s"))
        self.assertEqual(first.straight_windows_before, first.straight_windows_after)
        self.assertFalse(first.completes_board_straight)
        stretched = classify(board + [card_for("2s"), card_for("Ac")])
        self.assertEqual(stretched.board_size, 5)
        self.assertEqual(stretched.straight_windows_complete, 1)
        self.assertEqual(stretched.straight_windows_available, 3)
        self.assertEqual(stretched.rank_multiplicities, (1, 1, 1, 1, 1))
        self.assertEqual(stretched.high_rank, "A")

    def test_wheel_never_fourteen_high_on_board(self):
        """A2345 board textures as a completed 5-high window, never 14-high."""
        texture = classify(cards_for("Ac 2d 3h 4s 5c"))
        self.assertEqual(texture.straight_windows_complete, 1)
        # Nine run windows: only {2..6} shares three-plus ranks with A2345.
        self.assertEqual(texture.straight_windows_available, 3)
        self.assertEqual(texture.high_rank, "A")
        self.assertEqual(texture.high_band, "superhigh")

    def test_runout_isomorphism_boundary(self):
        """texture_after/booleans are isomorphism-invariant; `card` is not.

        RunoutDelta names the runout card (card identity), so it is the
        documented spec exception to suit-isomorphism invariance.
        """
        for number, fixture in enumerate(RUNOUT_FIXTURES):
            with self.subTest(fixture=number):
                base = cards_for(fixture["board"])
                runout = card_for(fixture["runout"])
                seed_delta = runout_delta(base, runout)
                rng = random.Random(900 + number)
                letters = list(_SUIT_ALPHABET)
                rng.shuffle(letters)
                mapping = str.maketrans(_SUIT_ALPHABET, "".join(letters))
                mapped_board = [
                    Card(card.rank, card.suit.translate(mapping)) for card in base
                ]
                mapped_runout = Card(
                    runout.rank, runout.suit.translate(mapping)
                )
                mapped = runout_delta(mapped_board, mapped_runout)
                self.assertEqual(mapped.texture_after, seed_delta.texture_after)
                self.assertEqual(mapped.texture_after, classify(mapped_board + [mapped_runout]))
                for field in ("pairs_board", "completes_flush", "extends_flush",
                              "straight_windows_before", "straight_windows_after",
                              "completes_board_straight"):
                    self.assertEqual(getattr(mapped, field), getattr(seed_delta, field))
                self.assertEqual(mapped.card, mapped_runout)


class IsomorphismInvarianceTest(unittest.TestCase):
    """classify is invariant under all suit relabelings (b, seeds 0..63)."""

    def test_suit_relabeling_seed_range(self):
        for seed in range(64):
            with self.subTest(seed=seed):
                rng = random.Random(seed)
                letters = list(_SUIT_ALPHABET)
                rng.shuffle(letters)
                mapping = str.maketrans(_SUIT_ALPHABET, "".join(letters))
                for board_spec in ISOMORPHISM_BOARDS:
                    board = cards_for(" ".join(board_spec))
                    mapped = [
                        Card(card.rank, card.suit.translate(mapping))
                        for card in board
                    ]
                    baseline = classify(board)
                    result = classify(mapped)
                    self.assertEqual(result, baseline, f"seed={seed} {board_spec}")
                    self.assertEqual(result.texture_key(), baseline.texture_key())

    def test_relabeled_runout_texture_after_invariant(self):
        for seed in range(64):
            with self.subTest(seed=seed):
                rng = random.Random(1000 + seed)
                letters = list(_SUIT_ALPHABET)
                rng.shuffle(letters)
                mapping = str.maketrans(_SUIT_ALPHABET, "".join(letters))
                base = cards_for("5c 4d 3h 2s")
                runout = card_for("9d")
                mapped = [
                    Card(card.rank, card.suit.translate(mapping))
                    for card in base + [runout]
                ]
                mapped_board, mapped_runout = mapped[:-1], mapped[-1]
                self.assertEqual(
                    runout_delta(mapped_board, mapped_runout).texture_after,
                    runout_delta(base, runout).texture_after,
                )


class ExhaustiveEnumerationTest(unittest.TestCase):
    """Exhaustive representative-class fixtures with closed-form landmarks (a).

    Every (rank multiset x canonical suit representative) board is verified
    field-by-field against the independent oracle, randomized determinism is
    re-probed, vocabulary membership is asserted, and aggregate totals are
    compared to closed-form arithmetic.  No per-rep ``subTest`` (runtime);
    failures carry the exact board in the message instead.
    """

    STREET_TOTALS = _ENUMERATION_TOTALS

    def test_exhaustive_street(self):
        for size in (3, 4, 5):
            with self.subTest(street=size):
                self._run_street(size)

    def _run_street(self, size: int) -> None:
        classify_calls = 0
        monotone_count = 0
        partitions_seen: set[tuple[int, ...]] = set()
        pairedness_seen: set[str] = set()
        combos_seen: set[tuple[str, str]] = set()
        multiset_count = 0
        rng = random.Random(7)
        monotone_bytes = b"c" * size
        for index, ranks in enumerate(itertools.combinations_with_replacement(RANKS, size)):
            if size == 5 and len(set(ranks)) == 1:
                continue  # rank multiplicity 5 is impossible (4 suits)
            multiset_count += 1
            multiplicities = tuple(sorted(Counter(ranks).values(), reverse=True))
            reps = _canonical_suit_reps(multiplicities)
            self.assertTrue(reps, f"no reps for {multiplicities}")
            rank_distinct = len(set(ranks)) == size
            sampled = index % 20 == 0
            contexts = (
                f"street {size} multiset {multiplicities}"
            )
            for suits in reps:
                board = _multiset_board(multiplicities, suits)
                texture = classify(board)
                classify_calls += 1
                oracle = oracle_classify(board)
                self.assertEqual(
                    texture, oracle,
                    lambda: (
                        f"{contexts} suits {suits!r} "
                        f"board {[card.symbol for card in board]} "
                        f"texture {texture} oracle {oracle}"
                    ),
                )
                partitions_seen.add(texture.rank_multiplicities)
                pairedness_seen.add(texture.pairedness)
                combos_seen.add((texture.pairedness, texture.suitedness))
                if sampled:
                    self.assertIn(texture.pairedness, PAIREDNESS_STATES)
                    self.assertIn(texture.suitedness, SUITEDNESS_STATES)
                    self.assertIn(texture.high_band, HIGH_CARD_BANDS)
                    for field in _BOARD_INT_FIELDS:
                        self.assertEqual(type(getattr(texture, field)), int, field)
                if suits == monotone_bytes:
                    monotone_count += 1
                    self.assertEqual(texture.suitedness, "monotone")
                    self.assertEqual(texture.pairedness, "no-pair")
                if size == 5 and (rank_distinct or index % 20 == 0):
                    self._cross_check_evaluator(texture, board)
                if rank_distinct and sampled:
                    # Determinism re-probe on representative samples.
                    shuffled = list(board)
                    rng.shuffle(shuffled)
                    self.assertEqual(classify(shuffled), texture)
                    self.assertEqual(classify(shuffled).texture_key(),
                                     texture.texture_key())
                    self.assertEqual(oracle_classify(shuffled), oracle)

        self.assertEqual(
            multiset_count, self.STREET_TOTALS[size],
            f"street {size} rank-multiset enumeration total",
        )
        self.assertEqual(
            monotone_count, _MONOTONE_TOTALS[size],
            f"street {size} monotone-representative total (closed form C(13,{size}))",
        )
        self.assertEqual(
            partitions_seen, _EXPECTED_PARTITIONS[size],
            f"street {size} observed partitions",
        )
        self.assertEqual(
            pairedness_seen, _EXPECTED_PAIREDNESS[size],
            f"street {size} observed pairedness cells",
        )
        self.assertEqual(
            combos_seen, _EXPECTED_COMBOS[size],
            f"street {size} observed pairedness x suitedness cells",
        )
        self.assertGreater(classify_calls, 0)

    def _cross_check_evaluator(self, texture: BoardTexture, board: list[Card]) -> None:
        """n=5 black-box evaluator oracle: windows <=> hand categories.

        ``straight_windows_complete > 0`` iff ``evaluate(board).category`` is
        STRAIGHT or STRAIGHT_FLUSH.  For five distinct ranks the property is
        suit-independent, so every multiset is checked on one representative
        plus every 20th paired-rank multiset per the docstring reduction.
        """
        category = evaluator.evaluate(board).category
        self.assertEqual(
            texture.straight_windows_complete > 0,
            category in (HandCategory.STRAIGHT, HandCategory.STRAIGHT_FLUSH),
            f"window/evaluator divergence on {b_symbols(board)}",
        )


def b_symbols(board) -> str:
    return " ".join(card.symbol for card in board)


class FailClosedTest(unittest.TestCase):
    """API fail-closed bounds mirroring the evaluator (d)."""

    def test_classify_rejects_wrong_card_counts(self):
        board3 = cards_for("As Ks Qs")
        too_few = board3[:2]
        too_many = board3 + [card_for("Js"), card_for("Ts"), card_for("9s")]
        for wrong in (too_few, too_many, []):
            with self.subTest(count=len(wrong)):
                with self.assertRaises(ValueError):
                    classify(wrong)

    def test_classify_rejects_non_card_items(self):
        for bad in (
            ["As", "Ks", "Qs"],            # untyped strings
            [None, Card("A", "s"), Card("K", "s")],
            [Card("A", "s"), Card("K", "s"), 42],
        ):
            with self.subTest(bad=bad):
                with self.assertRaises(TypeError):
                    classify(bad)

    def test_classify_rejects_card_subclass(self):
        class SubCard(Card):
            pass

        with self.assertRaises(TypeError):
            classify([SubCard("A", "s"), Card("K", "s"), Card("Q", "s")])

    def test_classify_rejects_duplicates(self):
        with self.assertRaises(ValueError):
            classify(cards_for("As As Ks"))
        with self.assertRaises(ValueError):
            classify(cards_for("As Ks Qs") + [card_for("As")])

    def test_classify_accepts_any_iterable(self):
        board = cards_for("As Ks Qs")
        self.assertEqual(classify(tuple(board)), classify(board))
        self.assertEqual(classify(card for card in board), classify(board))
        self.assertEqual(classify(reversed(board)), classify(board))

    def test_runout_delta_rejects_river_and_wrong_sizes(self):
        board5 = cards_for("As Ks Qs 2c 9d")
        board3 = cards_for("As Ks Qs")
        board2 = board3[:2]
        for bad_board in (board5, board2, []):
            with self.subTest(count=len(bad_board)):
                with self.assertRaises(ValueError):
                    runout_delta(bad_board, card_for("Js"))
        with self.assertRaises(ValueError):
            runout_delta(cards_for("As Ks Qs 2c 9d"), card_for("Jh"))

    def test_runout_delta_rejects_non_card_runout(self):
        board = cards_for("As Ks Qs 2c")
        for bad in (None, "Js", 7, Card("A", "s")):
            if isinstance(bad, Card):
                with self.subTest(bad="board card"):
                    with self.assertRaises(ValueError):
                        runout_delta(board, bad)
            else:
                with self.subTest(bad=bad):
                    with self.assertRaises(TypeError):
                        runout_delta(board, bad)

    def test_runout_delta_rejects_duplicate_board(self):
        with self.assertRaises(ValueError):
            runout_delta(cards_for("As As Ks"), card_for("Qd"))


class PurityDeterminismTest(unittest.TestCase):
    """Determinism, typing, vocabulary closure and frozen-ness (e)."""

    BOARDS = tuple(
        cards_for(spec) for spec in (
            "5s 4s 3h", "As 2s 3s", "Ks Kd 9h 4c", "As Ks 7s 2s",
            "Qh Qd Qc 7s", "8c 8d 8h 8s Kd", "Qd Qs Qc 3h 3s",
            "Ac 2d 3h 4s 5c", "As Ks Qs", "2c 3d 9h",
        )
    )

    def test_identical_input_identical_result(self):
        for board in self.BOARDS:
            with self.subTest(board=b_symbols(board)):
                first = classify(board)
                second = classify(list(reversed(board)))
                self.assertEqual(first, second)
                self.assertEqual(first.texture_key(), second.texture_key())
                self.assertEqual(hash(first.texture_key()), hash(second.texture_key()))

    def test_texture_key_is_hashable_canonical_tuple(self):
        for board in self.BOARDS:
            with self.subTest(board=b_symbols(board)):
                key = classify(board).texture_key()
                self.assertIsInstance(key, tuple)
                self.assertEqual(len(key), 10)
                key_copy = classify(list(board)).texture_key()
                self.assertEqual(key, key_copy)

    def test_numeric_fields_exactly_int(self):
        for board in self.BOARDS:
            texture = classify(board)
            for field in _BOARD_INT_FIELDS:
                value = getattr(texture, field)
                self.assertIs(type(value), int, f"{field}={value!r}")

    def test_vocabulary_closed_set(self):
        for board in self.BOARDS:
            texture = classify(board)
            with self.subTest(board=b_symbols(board)):
                self.assertIn(texture.pairedness, PAIREDNESS_STATES)
                self.assertIn(texture.suitedness, SUITEDNESS_STATES)
                self.assertIn(texture.high_band, HIGH_CARD_BANDS)
                self.assertIn(texture.high_rank, RANKS)
                self.assertIn(texture.max_suit_count, range(1, texture.board_size + 1))
                self.assertEqual(
                    texture.rank_multiplicities,
                    tuple(sorted(texture.rank_multiplicities, reverse=True)),
                )
                self.assertEqual(
                    sum(texture.rank_multiplicities), texture.board_size
                )

    def test_dataclasses_are_frozen(self):
        board = cards_for("As Ks Qs")
        texture = classify(board)
        delta = runout_delta(board, card_for("2s"))
        for frozen, field in ((texture, "pairedness"), (delta, "pairs_board")):
            with self.subTest(obj=type(frozen).__name__):
                with self.assertRaises(dataclasses.FrozenInstanceError):
                    setattr(frozen, field, "corrupted")

    def test_runout_field_types(self):
        delta = runout_delta(cards_for("As Ks Qs"), card_for("2s"))
        self.assertIs(type(delta.card), Card)
        self.assertIsInstance(delta.texture_after, BoardTexture)
        for field in ("pairs_board", "completes_flush", "extends_flush",
                      "completes_board_straight"):
            self.assertIs(type(getattr(delta, field)), bool, field)
        for field in ("straight_windows_before", "straight_windows_after"):
            self.assertIs(type(getattr(delta, field)), int, field)

    def test_version_pin(self):
        self.assertEqual(BOARD_TEXTURE_VERSION, "1.0.0")

    def test_board_module_does_not_import_evaluator(self):
        import poker.cards.board as board_module

        self.assertNotIn("evaluator", vars(board_module))


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
