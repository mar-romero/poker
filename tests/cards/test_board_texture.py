"""Test suite for ``poker.cards.board`` (task POKER-RANGE-BOARD-001).

Fixture strategy (tdd.mode='not_applicable'; the committed planner handoff is
the authoritative spec): exhaustive rank-multiset enumerations crossed with
isomorphism-reduced canonical suit-pattern representatives, wheel-edge and
flush-edge runout fixtures, seeded suit-relabeling invariance, fail-closed API
bounds and purity/determinism probes.  An independent definition-driven
oracle (``oracle_classify``) re-derives every ``BoardTexture`` field inside
this module only, deliberately differently from the production window scan
(dict membership counting versus frozenset intersection), so any vocabulary
or window-semantics mutation fails loud.

Exhaustive enumeration (AC2) covers every rank multiset with repetition per
street — n=3: C(15, 3) = 455, n=4: C(16, 4) = 1820, n=5: C(17, 5) - 13 = 6175
(the 13 impossible rank-multiplicity-5 multisets are excluded) — each crossed
with one canonical representative per S4 suit orbit, generated by a
restricted-growth relabeling rule ("suits are introduced in ``cdhs`` order")
whose correctness is itself verified against brute-force 24-permutation orbit
reduction.  Runtime reductions applied per the planner fallback rule, all
recorded here:

- Full exhaustive ``classify`` + oracle verification is retained for all
  streets and all rank multisets (no reduction).
- The brute-force orbit-reduction cross-check runs on every n=3 multiset and
  on every 25th (n=4) / every 100th (n=5) multiset (full cross-check per
  street would add minutes without strengthening the oracle-verified
  semantics).
- The n=5 black-box ``evaluator`` cross-check (``straight_windows_complete > 0
  iff STRAIGHT/STRAIGHT_FLUSH``) is rank-only, so it runs on one
  representative of every rank-distinct multiset (where completion is
  possible) and on the representatives of every 20th paired-rank multiset
  (where completion is impossible by construction).
- Determinism re-probes (shuffled input, ``texture_key`` stability) and
  per-rep type/vocabulary probes run on every 20th multiset per street;
  every representative still gets the full field-by-field oracle equality
  check, so any vocabulary or window-semantics mutation still fails.

Randomness discipline: only locally constructed ``random.Random(seed)``
instances; every randomized loop pins its seeds (0..63) with ``subTest``.
"""

